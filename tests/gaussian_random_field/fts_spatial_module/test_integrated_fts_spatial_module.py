"""
Run FTS on real input and assert that the output matches the recorded R result.

tests/test_data/watson_runoff_racmo55_grf_output.zarr has been generated by:
1. Running the DDM for dataset UC1_WATSON_RUNOFF_INPUT_RACMO55 from 2006-01-01 to 2026-01-01.
2. Running the GRF module on the DDM output with ``--mesh-name watsonmesh --grid-res-x 100 --grid-res-y 100``.
3. Compressing the GRF like so, to ensure the Zarr is small enough to store in the repo:

   ```python
   ds = xr.open_zarr(grf_output)[[VARIABLE, "spatial_ref"]].load()
   ds[VARIABLE] = ds[VARIABLE].astype(np.float32)
   for name in ds.variables:
      ds[name].encoding = {}
   compressor = BloscCodec(cname="zstd", clevel=9, shuffle=BloscShuffle.shuffle)
   encoding = {VARIABLE: {"chunks": ds[VARIABLE].shape, "compressors": [compressor]}}
   ds.to_zarr(FIXTURE_PATH, mode="w", consolidated=False, encoding=encoding)
   ```

tests/test_data/expected_results/watson_runoff_racmo55_fts.json was generated by running the FTS spatial analysis on the
fixture with params seen in the test and storing the resulting coefficients as JSON. The output was generated with
hdftsa 1.1 in R 4.6.1 to later validate that the Python implementation reproduces the same coefficients.
"""

import json
from pathlib import Path

import numpy as np
import xarray as xr
from conftest import assert_equal_up_to_column_sign

from gaussian_random_field.fts_spatial_module.fts_spatial_module import FtsSpatialModule


def test_watson_runoff_matches_the_recorded_r_result():
    """The sign of each column is arbitrary in R, so only agreement up to sign is required."""
    ds = xr.open_zarr("tests/test_data/test_inputs/watson_runoff_racmo55_grf_output.zarr").load()
    expected_path = Path("tests/test_data/expected_results/watson_runoff_racmo55_fts_output.json")
    reference = np.array(json.loads(expected_path.read_text()))

    output = FtsSpatialModule().run_spatial_analysis(ds, curve_time_points=5, num_pca=2, num_factors=3)
    result = output["log10_surface_runoff_amount"].values

    assert result.shape == reference.shape
    assert_equal_up_to_column_sign(result, reference, atol=1e-10 * np.abs(reference).max())
